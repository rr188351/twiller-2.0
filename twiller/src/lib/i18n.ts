export const dictionaries: LocaleDictionaries = {
  en,
  hi,
  es,
  pt,
  zh,
  fr,
};

/**
 * Resolves a dot path like "nav.home" against one dictionary.
 * Returns undefined (never throws) when any segment is missing.
 */
function resolvePath(
  dict: Record<string, unknown> | undefined,
  path: string
): string | undefined {
  if (!dict) return undefined;
  let node: unknown = dict;
  for (const segment of path.split(".")) {
    if (node === null || typeof node !== "object") return undefined;
    node = (node as Record<string, unknown>)[segment];
  }
  return typeof node === "string" ? node : undefined;
}

/**
 * Translate a dotted key. Lookup order: active locale -> English ->
 * the key path itself. A missing key degrades to English, never to a
 * crash or a blank page.
 *
 * Example: t("hi", "nav.home") === "होम"; t("hi", "nope.missing") falls
 * back to English or returns "nope.missing".
 */
export function t(
  locale: Locale,
  path: string,
  params?: Record<string, string>
): string {
  let hit = resolvePath(
    dictionaries[locale] as unknown as Record<string, unknown>,
    path
  );
  if (hit === undefined) {
    hit = resolvePath(
      en as unknown as Record<string, unknown>,
      path
    );
  }
  if (hit === undefined) return path;
  if (params) {
    for (const [key, value] of Object.entries(params)) {
      hit = hit.replace(new RegExp(`{${key}}`, "g"), value);
    }
  }
  return hit;
}

/**
 * Locale-aware date formatting for displayed dates (e.g. profile "Joined"
 * line). Tweets and stored values are never rewritten - only presentation.
 */
export function formatDate(
  locale: Locale,
  value: string | number | Date,
  options: Intl.DateTimeFormatOptions = { month: "long", year: "numeric" }
): string {
  try {
    const date = value instanceof Date ? value : new Date(value);
    if (Number.isNaN(date.getTime())) return String(value);
    return new Intl.DateTimeFormat(locale, options).format(date);
  } catch {
    return String(value);
  }
}