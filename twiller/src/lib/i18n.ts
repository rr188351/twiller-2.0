/**
 * Multilingual infrastructure - Internship Feature 4 (phase 1).
 *
 * WHY THIS FILE EXISTS
 * --------------------
 * Twiller renders every view as a client component switched by `currentPage`
 * state (`Mainlayout`), so translations live in one typed place instead of a
 * routing/URL scheme: a `LanguageContext` holds the active locale, and every
 * component calls `t(lang, "namespace.key")`. No i18n library is installed
 * and none is needed - the six dictionaries below are plain typed objects.
 *
 * RULES (per the phase scope)
 * ---------------------------
 * - Only UI chrome is translated: nav, headers, buttons, forms, validation,
 *   loading/empty/error text. NEVER tweet text, usernames, bios, plan names,
 *   prices, invoice identifiers, URLs or IDs.
 * - `t()` NEVER throws: unknown locales and missing keys fall back to
 *   English, and a totally unknown key returns the key path itself.
 * - Phase 1 is UI only: no OTP, no providers, no backend involvement.
 * - Language preference lives in `localStorage` under "twiller-locale"
 *   (see LanguageContext). It is device-local: it survives logout and
 *   account switches, but does not roam across browsers/devices and is
 *   never sent to the backend.
 */

export type Locale = "en" | "hi" | "es" | "pt" | "zh" | "fr";

export const LOCALES: Locale[] = ["en", "hi", "es", "pt", "zh", "fr"];

export const LOCALE_LABELS: Record<Locale, string> = {
  en: "English",
  hi: "हिन्दी",
  es: "Español",
  pt: "Português",
  zh: "中文",
  fr: "Français",
};

export const LOCALE_STORAGE_KEY = "twiller-locale";

export const DEFAULT_LOCALE: Locale = "en";

/** Accepts only the six known codes - anything else (typos, old values,
 *  tampered storage) resolves to English. */
export function parseLocale(value: unknown): Locale {
  if (typeof value === "string" && (LOCALES as string[]).includes(value)) {
    return value as Locale;
  }
  return DEFAULT_LOCALE;
}

